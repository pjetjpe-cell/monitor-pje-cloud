// Roda contra um servidor já iniciado (npm run build && npm start). BASE=http://localhost:3000 NODE_PATH=$(npm root -g) node e2e/calculadora-sem-pagamento.js
const BASE = process.env.BASE || 'http://localhost:3000'
const { chromium } = require('playwright')
const SP = process.env.SAIDA || '/tmp'
;(async () => {
  const b = await chromium.launch()
  const d = await b.newContext({ viewport: { width: 1360, height: 900 } })
  const p = await d.newPage()
  const erros = []
  p.on('pageerror', e => erros.push(e.message))
  p.on('console', m => m.type() === 'error' && erros.push(m.text()))
  await p.goto(BASE + '/')
  await p.screenshot({ path: `${SP}/home-desktop.png`, fullPage: true })
  await p.goto(BASE + '/calculadora')
  await p.fill('#empreendimento', 'Porto 2 Life')
  await p.fill('#dataCompra', '2021-03-10')
  await p.fill('#totalPago', '18.500,00')
  await p.click('text=Ver minha faixa estimada')
  await p.waitForSelector('#resultado')
  const faixa = await p.locator('#resultado p.font-serif').first().innerText()
  console.log('FAIXA:', faixa)
  await p.fill('#nome', 'Maria Teste')
  await p.fill('#whatsapp', '(81) 99999-0000')
  await p.fill('#email', 'maria@example.com')
  await p.fill('#numeroCota', '123/45')
  await p.check('input[type=checkbox] >> nth=-1')
  await p.screenshot({ path: `${SP}/calc-desktop.png`, fullPage: true })
  await p.click('text=Quero ser avisado')
  await p.waitForSelector('text=Recebemos seus dados')
  const href = await p.locator('a:has-text("Enviar número da cota")').getAttribute('href')
  console.log('WA:', decodeURIComponent(href).slice(0, 220))
  const r = await p.request.post(BASE + '/api/pedidos', { data: {} })
  console.log('PEDIDOS desabilitado:', r.status())
  const r2 = await p.request.get(BASE + '/api/pedidos/abcdefghijklmnopqrstuvwx/pdf')
  console.log('PDF token inexistente:', r2.status())
  const m = await b.newContext({ viewport: { width: 390, height: 800 }, deviceScaleFactor: 2 })
  const pm = await m.newPage()
  await pm.goto(BASE + '/')
  await pm.screenshot({ path: `${SP}/home-mobile.png`, fullPage: false })
  await pm.goto(BASE + '/calculadora')
  await pm.screenshot({ path: `${SP}/calc-mobile.png`, fullPage: false })
  const overflow = await pm.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  console.log('overflow horizontal mobile:', overflow)
  console.log('ERROS:', erros)
  await b.close()
})()
