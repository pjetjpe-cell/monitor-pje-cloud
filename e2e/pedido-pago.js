// Roda contra um servidor já iniciado (npm run build && npm start). BASE=http://localhost:3000 NODE_PATH=$(npm root -g) node e2e/pedido-pago.js
const BASE = process.env.BASE || 'http://localhost:3000'
const { chromium } = require('playwright')
const SP = process.env.SAIDA || '/tmp'
;(async () => {
  const b = await chromium.launch()
  const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
  const erros = []
  p.on('pageerror', e => erros.push(e.message))
  await p.goto(BASE + '/calculadora')
  await p.fill('#empreendimento', 'Gran Valley')
  await p.click('text=Pagamento a pagamento')
  await p.fill('#dataCompra', '2022-05-10')
  await p.fill('[aria-label="Data do pagamento 1"]', '2022-05-10')
  await p.fill('[aria-label="Valor do pagamento 1"]', '5.000,00')
  await p.click('text=+ Adicionar pagamento')
  await p.fill('[aria-label="Data do pagamento 2"]', '2023-06-10')
  await p.fill('[aria-label="Valor do pagamento 2"]', '650,50')
  await p.check('text=Paguei comissão de corretagem na compra')
  await p.fill('#corretagem', '1.000,00')
  await p.click('text=Ver minha faixa estimada')
  await p.waitForSelector('#resultado')
  await p.fill('#nome', 'João da Silva')
  await p.fill('#whatsapp', '81988887777')
  await p.fill('#email', 'joao@example.com')
  await p.fill('#numeroCota', '77/12')
  await p.check('input[type=checkbox] >> nth=-1')
  await Promise.all([p.waitForURL(/\/relatorio\//), p.click('text=Continuar para o pagamento')])
  const url = p.url(); const token = url.split('/relatorio/')[1]
  console.log('PEDIDO URL OK', token.length)
  await p.waitForSelector('textarea')
  const payload = await p.inputValue('textarea')
  console.log('PIX payload:', payload.slice(0, 60) + '…', payload.length)
  await p.screenshot({ path: `${SP}/pedido.png`, fullPage: true })
  let r = await p.request.get(`${BASE}/api/pedidos/${token}/pdf`)
  console.log('PDF antes de pagar:', r.status())
  await p.click('text=Já paguei')
  await p.waitForSelector('text=Pagamento em conferência')
  r = await p.request.get(`${BASE}/api/pedidos/${token}/pdf`)
  console.log('PDF em conferência:', r.status())
  // Admin confirma
  const a = await (await b.newContext()).newPage()
  await a.goto(BASE + '/login')
  await a.fill('input[type=email]', 'admin@dipallacio.example')
  await a.fill('input[type=password]', 'admin123')
  await a.click('button[type=submit]')
  await a.waitForURL(u => !u.pathname.startsWith('/login'))
  await a.goto(BASE + '/admin/pedidos')
  await a.screenshot({ path: `${SP}/admin-pedidos.png` })
  a.on('dialog', d => d.accept())
  await a.click('text=Confirmar pagamento recebido >> nth=0')
  await a.waitForSelector('text=Pago')
  r = await p.request.get(`${BASE}/api/pedidos/${token}/pdf`)
  const buf = await r.body()
  console.log('PDF após confirmação:', r.status(), r.headers()['content-type'], buf.slice(0, 5).toString(), buf.length)
  require('fs').writeFileSync(`${SP}/baixado.pdf`, buf)
  await p.reload()
  await p.waitForSelector('text=Baixar relatório em PDF')
  await p.screenshot({ path: `${SP}/pedido-pago.png`, fullPage: true })
  console.log('ERROS:', erros)
  await b.close()
})()
